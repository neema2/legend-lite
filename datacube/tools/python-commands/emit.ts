import { PAGE_COMMAND_FIELDS, PAGE_COMMAND_KINDS } from '../../src/page-commands.ts';

/** Python's own words, never a parameter's name: such a field's parameter ends in `_`. */
const KEYWORDS = new Set([
  'False', 'None', 'True', 'and', 'as', 'assert', 'async', 'await', 'break', 'class', 'continue', 'def', 'del', 'elif',
  'else', 'except', 'finally', 'for', 'from', 'global', 'if', 'import', 'in', 'is', 'lambda', 'nonlocal', 'not', 'or',
  'pass', 'raise', 'return', 'try', 'while', 'with', 'yield',
]);

const snake = (name: string): string => name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
const parameter = (field: string): string => (KEYWORDS.has(snake(field)) ? `${snake(field)}_` : snake(field));

function builder(prefix: string, kind: string, listed: readonly string[]): string {
  const fields = listed.map((f) => ({ name: f.replace(/\?$/, ''), optional: f.endsWith('?') }));
  const signature = fields.length === 0 ? '' : `*, ${fields
    .map((f) => `${parameter(f.name)}: Any${f.optional ? ' = _ABSENT' : ''}`).join(', ')}`;
  const entries = fields.map((f) => (f.optional
    ? `**({} if ${parameter(f.name)} is _ABSENT else {'${f.name}': ${parameter(f.name)}})`
    : `'${f.name}': ${parameter(f.name)}`));
  const head = `def ${prefix}_${snake(kind)}(${signature}) -> dict[str, Any]:`;
  const body = `    return {'kind': '${kind}'${entries.map((e) => `, ${e}`).join('')}}`;
  return `${wrap(head, head.indexOf('('))}\n${wrap(body, body.indexOf('{'))}\n`;
}

/** A line of at most 120 characters: broken after a comma between the items the bracket at `open` holds (never inside a
 *  string or a nested bracket), each line after aligned under that bracket's first item, as PEP 8 aligns them. */
function wrap(line: string, open: number): string {
  if (line.length <= 120) return line;
  const breaks: number[] = [];
  let depth = 0;
  let quoted = false;
  for (let i = open; i < line.length; i += 1) {
    const c = line[i]!;
    if (c === "'") quoted = !quoted;
    if (quoted) continue;
    if ('([{'.includes(c)) depth += 1;
    else if (')]}'.includes(c)) {
      depth -= 1;
      if (depth === 0) break;
    } else if (c === ',' && depth === 1 && line[i + 1] === ' ') breaks.push(i);
  }
  const indent = ' '.repeat(open + 1);
  const out: string[] = [];
  let from = 0;
  let last = -1;
  for (const at of [...breaks, line.length]) {
    const width = (out.length === 0 ? 0 : indent.length) + (at - from) + 1;
    if (width > 120 && last >= 0) {
      out.push((out.length === 0 ? '' : indent) + line.slice(from, last + 1));
      from = last + 2;
    }
    last = at;
  }
  out.push((out.length === 0 ? '' : indent) + line.slice(from));
  return out.join('\n');
}

const kindList = (name: string, kinds: readonly string[]): string => {
  const line = `${name}: tuple[str, ...] = (${kinds.map((k) => `'${k}'`).join(', ')},)`;
  return wrap(line, line.indexOf(' = (') + 3);
};

