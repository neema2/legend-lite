"""THE WORLD'S COUNTRIES, prepared for DataCube's maps (docs/DATACUBE_CHARTS_DESIGN_2026_10_09.md §4; the roadmap run's
phase 6). Run once, its output committed with how it was made (§6 open 2, the committed choice): Natural Earth's
1:110m countries (public domain), the ISO view, as published at the release this pins -- the published file's sha256
checked, so the output is reproducible from it.

What it does, and only that:
- keeps each country's geometry as published, every coordinate rounded to 2 decimals (about a kilometre; 1:110m draws
  nothing finer). A rounded vertex is the same on both sides of a shared border, so neighbours still meet exactly;
- keeps the five fields a map matches a column by: the ISO 3166 alpha-3 and alpha-2 codes (Natural Earth's `_EH`
  fields, which give France and Norway theirs; a territory with none has null), the short name, the long name and the
  administrative name;
- writes it as a TypeScript module, its own chunk, fetched when a map first draws (datacube/src/maps/world-110m.ts).

Standard library only. Usage (from the repository root):

    curl -sSo /tmp/ne.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_admin_0_countries.geojson
    python3 -I datacube/tools/maps/prepare.py /tmp/ne.geojson datacube/src/maps/world-110m.ts
"""

from __future__ import annotations

import hashlib
import json
import sys

RELEASE = 'v5.1.2'
SOURCE = f'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/{RELEASE}/geojson/ne_110m_admin_0_countries.geojson'
SHA256 = '6866c877d39cba9c357620878839b336d569f8c662d3cfab4cb1dbe2d39c977f'
DECIMALS = 2


def rounded(coordinates):
    if isinstance(coordinates[0], (int, float)):
        return [round(coordinates[0], DECIMALS), round(coordinates[1], DECIMALS)]
    return [rounded(c) for c in coordinates]


def code(value):
    # Natural Earth writes "-99" where a territory has no ISO code
    return None if value in (None, '-99') else value


def prepare(published: bytes) -> str:
    digest = hashlib.sha256(published).hexdigest()
    if digest != SHA256:
        raise SystemExit(f'the published file is not the one pinned: sha256 {digest}, expected {SHA256}')
    features = []
    for f in json.loads(published)['features']:
        p = f['properties']
        features.append({
            'type': 'Feature',
            'properties': {'iso3': code(p['ISO_A3_EH']), 'iso2': code(p['ISO_A2_EH']), 'name': p['NAME'],
                           'long': p['NAME_LONG'], 'admin': p['ADMIN']},
            'geometry': {'type': f['geometry']['type'], 'coordinates': rounded(f['geometry']['coordinates'])},
        })
    features.sort(key=lambda f: f['properties']['name'])
    shapes = json.dumps({'type': 'FeatureCollection', 'features': features}, separators=(',', ':'), ensure_ascii=False)
    return (
        '// GENERATED by datacube/tools/maps/prepare.py -- DO NOT EDIT. Natural Earth 1:110m countries (public domain),\n'
        f'// release {RELEASE}, as published (sha256 {SHA256}),\n'
        f'// every coordinate rounded to {DECIMALS} decimals, five fields kept. docs/DATACUBE_CHARTS_DESIGN_2026_10_09.md §4.\n'
        '// Its own chunk: fetched when a map first draws.\n'
        '\n'
        "import type { WorldShapes } from './shapes.ts';\n"
        '\n'
        f'export const WORLD_SOURCE = {json.dumps(SOURCE)};\n'
        '\n'
        f'export const WORLD_110M: WorldShapes = {shapes};\n'
    )


def main(argv: list[str]) -> None:
    if len(argv) != 3:
        raise SystemExit('usage: prepare.py <published geojson> <out .ts>')
    with open(argv[1], 'rb') as f:
        out = prepare(f.read())
    with open(argv[2], 'w', encoding='utf-8') as f:
        f.write(out)


if __name__ == '__main__':
    main(sys.argv)
