package tscatalog;

import com.legend.Compiler;
import com.legend.compiler.element.ModelContext;
import com.legend.compiler.spec.TsIslands;
import com.legend.protocol.ts.TsCatalog;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * THE CATALOG, EXPORTED (docs/TS_LIBRARY_DEFINES_THE_LANGUAGE_2026_10_31.md, S5): what the clients read of the
 * library, written from the library itself as core compiles it -- never parsed from its text again by a tool of its
 * own. {@code bazel run //datacube:update_generated} copies them in; their diff tests
 * fail the build when the library changes a word or an option and they are not regenerated.
 *
 * <ul>
 *   <li>{@code library-enums.ts}: each enumeration of {@code timeseries}, its values in their declared order (what the
 *       tile's catalog and writer read: an option's one source).</li>
 *   <li>{@code ts-words.ts}: every word of {@code #TS}, its parameters by place (their kinds, a span's forms, an
 *       option's words, whether a call must give one), its forms and its description.</li>
 *   <li>{@code WORDS.md}: the guide's page of the words, the same facts as prose.</li>
 * </ul>
 *
 * <p>Usage: {@code TsCatalogExport <model.pure> <library-enums.ts> <ts-words.ts> <WORDS.md>}.
 */
public final class TsCatalogExport {

    private TsCatalogExport() {
    }

    public static void main(String[] args) throws Exception {
        ModelContext model = Compiler.compileModel(Files.readString(Path.of(args[0]), StandardCharsets.UTF_8));
        Map<String, List<String>> enums = TsIslands.enumerations(model, "timeseries");
        List<TsCatalog.Word> words = TsIslands.catalog(model);
        Files.writeString(Path.of(args[1]), enumsTs(enums), StandardCharsets.UTF_8);
        Files.writeString(Path.of(args[2]), wordsTs(words), StandardCharsets.UTF_8);
        Files.writeString(Path.of(args[3]), wordsMd(words), StandardCharsets.UTF_8);
    }

    private static String quote(String s) {
        return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'";
    }

    private static String enumsTs(Map<String, List<String>> enums) {
        List<String> out = new ArrayList<>(List.of(
                "// GENERATED by core's TsCatalogExport from projects/timeseries/model.pure as core compiles it (the library's own",
                "// enumerations) -- DO NOT EDIT. Regenerate: bazel run //datacube:update_generated; its diff test fails the build if",
                "// this copy drifts from the library.",
                "",
                "/** Each enumeration of timeseries by its name, its values in their declared order: the one source of an option's",
                " *  values, which the catalog's words and the writer's check both read. */",
                "export const LIBRARY_ENUMS = {"));
        enums.forEach((name, values) -> out.add("  " + name + ": [" + values.stream().map(TsCatalogExport::quote)
                .collect(Collectors.joining(", ")) + "],"));
        out.addAll(List.of("} as const;", "", "/** An enumeration of timeseries. */",
                "export type LibraryEnum = keyof typeof LIBRARY_ENUMS;", ""));
        return String.join("\n", out);
    }

    private static String list(List<String> xs) {
        return "[" + xs.stream().map(TsCatalogExport::quote).collect(Collectors.joining(", ")) + "]";
    }

    private static String wordsTs(List<TsCatalog.Word> words) {
        List<String> out = new ArrayList<>(List.of(
                "// GENERATED by core's TsCatalogExport from projects/timeseries/model.pure as core compiles it -- DO NOT EDIT.",
                "// Regenerate: bazel run //datacube:update_generated; its diff test fails the build if this copy drifts.",
                "//",
                "// THE WORDS OF #TS (docs/TS_LIBRARY_DEFINES_THE_LANGUAGE_2026_10_31.md M3, S5): each a timeseries::line:: function",
                "// of the library, its parameters by place as #TS binds them (TsCatalog), its forms and its description -- what a",
                "// formula box completes and a help page says.",
                "",
                "/** A parameter of a word: its kind (line, line_or_number, members, span, whole, number, word, date, since), what",
                " *  a span takes (observations, period, all, date), an option's words, and whether a call must give it. */",
                "export interface TsWordParam {",
                "  readonly name: string;",
                "  readonly kind: string;",
                "  readonly takes: readonly string[];",
                "  readonly words: readonly string[];",
                "  readonly required: boolean;",
                "}",
                "",
                "/** A word: its parameters by place, its forms (each overload as written), its description, its other",
                " *  spellings (the library's timeseries::Words.alias: mean's avg), and its facts -- the library's other",
                " *  timeseries::Words tags by name (label, family, unit, level, bounds, gsQuant, about, differs, param, search)",
                " *  and its stereotypes (band, candles, anchored): what a drawing and a formula box know of it. */",
                "export interface TsWord {",
                "  readonly params: readonly TsWordParam[];",
                "  readonly forms: readonly string[];",
                "  readonly doc: string | null;",
                "  readonly aliases: readonly string[];",
                "  readonly facts: Readonly<Record<string, readonly string[]>>;",
                "  readonly marks: readonly string[];",
                "}",
                "",
                "/** Every word, by its name. */",
                "export const TS_WORDS: Readonly<Record<string, TsWord>> = {"));
        for (TsCatalog.Word w : words) {
            out.add("  " + w.name() + ": {");
            out.add("    params: [");
            for (TsCatalog.Param p : w.params()) {
                out.add("      { name: " + quote(p.name()) + ", kind: " + quote(p.kind()) + ", takes: " + list(p.takes())
                        + ", words: " + list(p.words()) + ", required: " + p.required() + " },");
            }
            out.add("    ],");
            out.add("    forms: " + list(w.forms()) + ",");
            out.add("    doc: " + (w.doc() == null ? "null" : quote(w.doc())) + ",");
            out.add("    aliases: " + list(w.aliases()) + ",");
            out.add("    facts: {" + w.facts().entrySet().stream().map(e -> " " + e.getKey() + ": " + list(e.getValue()))
                    .collect(Collectors.joining(",")) + (w.facts().isEmpty() ? "}," : " },"));
            out.add("    marks: " + list(w.marks()) + ",");
            out.add("  },");
        }
        out.addAll(List.of("};", ""));
        return String.join("\n", out);
    }

    private static String wordsMd(List<TsCatalog.Word> words) {
        List<String> out = new ArrayList<>(List.of(
                "<!-- GENERATED by core's TsCatalogExport from projects/timeseries/model.pure -- DO NOT EDIT.",
                "     Regenerate: bazel run //docs:update_ts_words. -->",
                "",
                "# The words of `#TS`",
                "",
                "Every word is a `timeseries::line::` function of the timeseries library (`projects/timeseries/model.pure`):",
                "what it computes is its Pure, what follows is read from its overloads as core compiles them. A word's",
                "lines come first; a parameter not required has the library's default. A span is a window or a lag: a number",
                "of observations (`20`), a calendar period (`3mo`), `all` (the line's start to date), or a date on",
                "(`'2024-01-01'`), as the word's forms allow.",
                ""));
        for (TsCatalog.Word w : words) {
            out.add("## `" + w.name() + "`");
            out.add("");
            if (w.doc() != null) {
                out.add(w.doc());
                out.add("");
            }
            if (!w.aliases().isEmpty()) {
                out.add("Also written " + w.aliases().stream().map(a -> "`" + a + "`").collect(Collectors.joining(", "))
                        + ".");
                out.add("");
            }
            out.add("| Parameter | Kind | Takes | Required |");
            out.add("|---|---|---|---|");
            for (TsCatalog.Param p : w.params()) {
                String takes = !p.takes().isEmpty() ? String.join(", ", p.takes())
                        : !p.words().isEmpty() ? String.join(", ", p.words()) : "";
                out.add("| `" + p.name() + "` | " + p.kind() + " | " + takes + " | " + (p.required() ? "yes" : "no")
                        + " |");
            }
            out.add("");
            out.add("Forms: " + w.forms().stream().map(f -> "`" + f + "`").collect(Collectors.joining(", ")) + ".");
            out.add("");
        }
        return String.join("\n", out);
    }
}
