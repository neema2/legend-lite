package tscatalog;

import com.legend.Compiler;
import com.legend.compiler.element.ModelContext;
import com.legend.compiler.spec.TsIslands;
import com.legend.protocol.ts.TsCatalog;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.stream.Collectors;

/**
 * THE CATALOG, EXPORTED (docs/TS_LIBRARY_DEFINES_THE_LANGUAGE_2026_10_31.md, S5): what the clients read of the
 * library, written from the library itself as core compiles it -- never parsed from its text again by a tool of its
 * own. {@code bazel run //datacube:update_generated} copies them in; their diff tests
 * fail the build when the library changes a word or an option and they are not regenerated.
 *
 * <ul>
 *   <li>{@code library-enums.ts}: each enumeration of {@code timeseries}, its values in their declared order (what the
 *       tile's catalog and writer read: an option's one source).</li>
 *   <li>{@code ts-words.ts}: every word of {@code #TS}, its parameters by place (their kinds, a span's forms, an
 *       option's words, whether a call must give one), its forms and its description.</li>
 *   <li>{@code WORDS.md}: the guide's page of the words, the same facts as prose.</li>
 *   <li>{@code ts-signatures.ts}: each word's signature as the tile and the builders read it -- its lines, its
 *       parameters' kinds, the library's stated defaults and limits ({@code timeseries::Words.given}, {@code .limit}),
 *       whether a call gives one, and gs-quant's default of a parameter gs-quant names alike (read from gs-quant itself:
 *       projects/timeseries/gs-quant-signatures.json, tools/ts-oracle/signatures.py) -- in place of the tile's
 *       hand-kept table (docs/TS_DECISIONS_2026_11_07.md §4, the order's step 1).</li>
 *   <li>{@code ts-facts.ts}: each word's facts as the tile tells them (its label, family, unit, what it computes, where
 *       it differs, its parameters said, how it is drawn): the library's tags, in place of the tile's hand-kept words; a
 *       module of its own, fetched with a tile, where the signatures are read at a page's start.</li>
 * </ul>
 *
 * <p>Usage: {@code TsCatalogExport <model.pure> <library-enums.ts> <ts-words.ts> <WORDS.md> <gs-quant-signatures.json>
 * <ts-signatures.ts> <ts-facts.ts>}.
 */
public final class TsCatalogExport {

    private TsCatalogExport() {
    }

    public static void main(String[] args) throws Exception {
        ModelContext model = Compiler.compileModel(Files.readString(Path.of(args[0]), StandardCharsets.UTF_8));
        Map<String, List<String>> enums = TsIslands.enumerations(model, "timeseries");
        List<TsCatalog.Word> words = TsIslands.catalog(model);
        Files.writeString(Path.of(args[1]), enumsTs(enums), StandardCharsets.UTF_8);
        Files.writeString(Path.of(args[2]), wordsTs(words), StandardCharsets.UTF_8);
        Files.writeString(Path.of(args[3]), wordsMd(words), StandardCharsets.UTF_8);
        Object gsq = plain(com.legend.json.Json.parse(Files.readString(Path.of(args[4]), StandardCharsets.UTF_8)));
        Files.writeString(Path.of(args[5]), signaturesTs(words, gsq), StandardCharsets.UTF_8);
        Files.writeString(Path.of(args[6]), factsTs(words), StandardCharsets.UTF_8);
    }

    /** JSON's null, as {@link #plain} holds it. */
    private static final Object JSON_NULL = new Object();

    /** A JSON node as plain values: a map, a list, a string, a number, a boolean, {@link #JSON_NULL}. */
    private static Object plain(com.legend.json.Json.Node n) {
        return switch (n) {
            case com.legend.json.Json.Obj o -> {
                Map<String, Object> m = new java.util.LinkedHashMap<>();
                o.fields().forEach((k, v) -> m.put(k, plain(v)));
                yield m;
            }
            case com.legend.json.Json.Arr a -> a.items().stream().map(TsCatalogExport::plain).toList();
            case com.legend.json.Json.Str x -> x.value();
            case com.legend.json.Json.Num x -> x.isInteger() ? (Object) x.longValue() : (Object) x.doubleValue();
            case com.legend.json.Json.Bool x -> x.value();
            case com.legend.json.Json.Null x -> JSON_NULL;
        };
    }

    /** The kinds of a parameter the tile writes (its lines apart: their count is its series; a date the tile reads is
     *  no parameter of its yet). */
    private static final java.util.Set<String> WRITTEN = java.util.Set.of("span", "whole", "number", "word");

    private static String signaturesTs(List<TsCatalog.Word> words, Object gsq) {
        List<String> out = new ArrayList<>(List.of(
                "// GENERATED by core's TsCatalogExport from projects/timeseries/model.pure as core compiles it, and from",
                "// projects/timeseries/gs-quant-signatures.json (gs-quant's own) -- DO NOT EDIT. Regenerate: bazel run",
                "// //datacube:update_generated; its diff test fails the build if this copy drifts.",
                "//",
                "// EACH WORD'S SIGNATURE (docs/TS_DECISIONS_2026_11_07.md §4, the order's step 1): its lines (`series`, their",
                "// roles where they are no x and y: `reads`), then its parameters by place -- each its kind, the library's stated",
                "// default (`default`: the language's where a call leaves it out, proved by",
                "// TsIslandTest.everyWordsStatedDefaultIsItsCallWithoutIt), its limits, whether every call gives it",
                "// (`required`), an option's words, and gs-quant's default of a parameter gs-quant names alike (`gsQuant`:",
                "// what a word is begun with where the language has none -- the builders' rule). A window or a lag of all",
                "// observations is 0, a calendar period the tile's spelling (3m).",
                "",
                "import type { TsSignature } from '../timeseries-spec.ts';",
                "",
                "/** Every word's signature, by its name. */",
                "export const WORD_SIGNATURES: Readonly<Record<string, TsSignature>> = {"));
        Map<?, ?> gsWords = gsq instanceof Map<?, ?> m && m.get("words") instanceof Map<?, ?> w ? w : Map.of();
        for (TsCatalog.Word w : words) {
            List<TsCatalog.Param> lines = w.params().stream().filter(p -> p.kind().startsWith("line")
                    || p.kind().equals("members")).toList();
            boolean members = lines.stream().anyMatch(p -> p.kind().equals("members"));
            List<String> names = lines.stream().map(TsCatalog.Param::name).toList();
            boolean plain = names.equals(List.of("x")) || names.equals(List.of("x", "y"));
            Map<String, String> given = tagged(w, "given");
            Map<String, String> limit = tagged(w, "limit");
            Map<String, Object> gs = gsDefaults(gsWords.get(w.name()));
            List<String> params = new ArrayList<>();
            for (TsCatalog.Param p : w.params()) {
                if (!WRITTEN.contains(p.kind())) {
                    continue;
                }
                StringBuilder b = new StringBuilder("{ name: " + quote(p.name()) + ", kind: " + quote(p.kind()));
                String d = given.get(p.name());
                if (d != null) {
                    b.append(", default: ").append(literal(p.kind(), d));
                }
                if (!p.words().isEmpty()) {
                    b.append(", words: ").append(list(p.words()));
                }
                String l = limit.get(p.name());
                if (l != null) {
                    for (String bound : l.split(",\\s*")) {
                        String[] op = bound.trim().split("\\s+", 2);
                        String key = switch (op[0]) {
                            case ">=" -> "min";
                            case ">" -> "above";
                            case "<" -> "below";
                            case "<=" -> "max";
                            default -> throw new IllegalStateException(w.name() + "'s limit " + bound);
                        };
                        b.append(", ").append(key).append(": ").append(op[1]);
                    }
                }
                String begun = tagged(w, "begun").get(p.name());
                if (begun != null) {
                    b.append(", begin: ").append(literal(p.kind(), begun));
                }
                if (p.kind().equals("span") && p.takes().contains("whole")) {
                    b.append(", whole: true");
                }
                b.append(", required: ").append(p.required());
                Object g = gs.get(p.name());
                String gl = g == null ? "" : gsLiteral(p, g);
                if (!gl.isEmpty()) {
                    b.append(", gsQuant: ").append(gl);
                }
                params.add(b.append(" }").toString());
            }
            out.add("  " + w.name() + ": { series: " + (members ? "'many'" : String.valueOf(lines.size()))
                    + (plain || members ? "" : ", reads: " + list(names)) + ", params: [" + String.join(", ", params)
                    + "] },");
        }
        out.addAll(List.of("};", ""));
        return String.join("\n", out);
    }

    /** The words' facts, a module of their own: what a tile says of a word, fetched with the tile (a page's start reads
     *  the signatures alone, to judge a saved series). */
    private static String factsTs(List<TsCatalog.Word> words) {
        List<String> out = new ArrayList<>(List.of(
                "// GENERATED by core's TsCatalogExport from projects/timeseries/model.pure as core compiles it -- DO NOT EDIT.",
                "// Regenerate: bazel run //datacube:update_generated; its diff test fails the build if this copy drifts.",
                "",
                "import type { TsWords } from '../timeseries-expr.ts';",
                "",
                "/** EACH WORD'S FACTS as the tile tells them: its label, family, unit, what it is a level of, its bounds, its",
                " *  gs-quant function, what it computes and where it differs, its parameters said, its other spellings typed, and",
                " *  how it is drawn (a band, candles, from the first date shown) -- the library's timeseries::Words tags and",
                " *  stereotypes, a word of every one the tile needs (label, family, unit, about, gsQuant) alone. */",
                "export const WORD_FACTS: Readonly<Record<string, TsWords>> = {"));
        for (TsCatalog.Word w : words) {
            Map<String, List<String>> f = w.facts();
            if (!List.of("label", "family", "unit", "about", "gsQuant").stream().allMatch(t -> f.containsKey(t))) {
                continue;
            }
            List<String> facts = new ArrayList<>();
            for (String tag : List.of("label", "family", "unit", "level", "gsQuant", "about", "differs")) {
                List<String> values = f.getOrDefault(tag, List.of());
                if (values.size() > 1) {
                    throw new IllegalStateException(w.name() + "'s " + tag + " said " + values.size() + " times");
                }
                if (!values.isEmpty()) {
                    facts.add(tag + ": " + quote(values.get(0)));
                }
            }
            List<String> bounds = f.getOrDefault("bounds", List.of());
            if (!bounds.isEmpty()) {
                facts.add("bounds: [" + bounds.get(0) + "]");
            }
            Map<String, String> said = tagged(w, "param");
            if (!said.isEmpty()) {
                facts.add("params: { " + said.entrySet().stream().map(e -> e.getKey() + ": " + quote(e.getValue()))
                        .collect(Collectors.joining(", ")) + " }");
            }
            List<String> search = f.getOrDefault("search", List.of());
            if (!search.isEmpty()) {
                facts.add("aliases: " + list(search));
            }
            for (String mark : List.of("band", "candles", "anchored")) {
                if (w.marks().contains(mark)) {
                    facts.add(mark + ": true");
                }
            }
            out.add("  " + w.name() + ": { " + String.join(", ", facts) + " },");
        }
        out.addAll(List.of("};", ""));
        return String.join("\n", out);
    }

    /** A word's tags of `tag` (`name: value`), by the parameter they are of. */
    private static Map<String, String> tagged(TsCatalog.Word w, String tag) {
        Map<String, String> out = new java.util.LinkedHashMap<>();
        for (String v : w.facts().getOrDefault(tag, List.of())) {
            int at = v.indexOf(": ");
            out.put(v.substring(0, at), v.substring(at + 2));
        }
        return out;
    }

    /** A stated default as the tile holds it: a window of all 0, a number a number, a calendar period its spelling. */
    private static String literal(String kind, String value) {
        if (kind.equals("span") && value.equals("all")) {
            return "0";
        }
        if (value.matches("-?[0-9]+(\\.[0-9]+)?")) {
            return value;
        }
        if (kind.equals("span")) {
            return quote(value.replaceAll("mo$", "m"));
        }
        return quote(value);
    }

    /** gs-quant's defaults of its first function's parameters, by name (its signature as gs-quant reads it). */
    private static Map<String, Object> gsDefaults(Object sigs) {
        Map<String, Object> out = new java.util.LinkedHashMap<>();
        if (sigs instanceof List<?> l && !l.isEmpty() && l.get(0) instanceof Map<?, ?> first
                && first.get("params") instanceof List<?> ps) {
            for (Object o : ps) {
                if (o instanceof Map<?, ?> p && p.get("name") instanceof String n && p.get("default") instanceof Map<?, ?>) {
                    out.put(n, p.get("default"));
                }
            }
        }
        return out;
    }

    /** gs-quant's default as the tile holds it, where it is one the parameter takes: a Window of no size every
     *  observation (0), of a size its size; an enumeration's member its word where the parameter's words have it --
     *  none ("") where it is no value the parameter takes. */
    private static String gsLiteral(TsCatalog.Param p, Object d) {
        if (!(d instanceof Map<?, ?> m)) {
            return "";
        }
        if (m.get("window") instanceof List<?> w && p.kind().equals("span")) {
            Object size = w.get(0);
            return size == JSON_NULL ? "0" : size instanceof Number n ? String.valueOf(n.longValue())
                    : quote(String.valueOf(size).replaceAll("mo$", "m"));
        }
        if (m.get("member") instanceof String member && p.kind().equals("word")) {
            String word = member.toLowerCase(java.util.Locale.ROOT);
            return p.words().contains(word) ? quote(word) : "";
        }
        if (m.get("value") instanceof Number n && !p.kind().equals("word")) {
            return n.doubleValue() == Math.rint(n.doubleValue()) ? String.valueOf(n.longValue()) : String.valueOf(n);
        }
        return "";
    }

    private static String quote(String s) {
        return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'";
    }

    private static String enumsTs(Map<String, List<String>> enums) {
        List<String> out = new ArrayList<>(List.of(
                "// GENERATED by core's TsCatalogExport from projects/timeseries/model.pure as core compiles it (the library's own",
                "// enumerations) -- DO NOT EDIT. Regenerate: bazel run //datacube:update_generated; its diff test fails the build if",
                "// this copy drifts from the library.",
                "",
                "/** Each enumeration of timeseries by its name, its values in their declared order: the one source of an option's",
                " *  values, which the catalog's words and the writer's check both read. */",
                "export const LIBRARY_ENUMS = {"));
        enums.forEach((name, values) -> out.add("  " + name + ": [" + values.stream().map(TsCatalogExport::quote)
                .collect(Collectors.joining(", ")) + "],"));
        out.addAll(List.of("} as const;", "", "/** An enumeration of timeseries. */",
                "export type LibraryEnum = keyof typeof LIBRARY_ENUMS;", ""));
        return String.join("\n", out);
    }

    private static String list(List<String> xs) {
        return "[" + xs.stream().map(TsCatalogExport::quote).collect(Collectors.joining(", ")) + "]";
    }

    private static String wordsTs(List<TsCatalog.Word> words) {
        List<String> out = new ArrayList<>(List.of(
                "// GENERATED by core's TsCatalogExport from projects/timeseries/model.pure as core compiles it -- DO NOT EDIT.",
                "// Regenerate: bazel run //datacube:update_generated; its diff test fails the build if this copy drifts.",
                "//",
                "// THE WORDS OF #TS (docs/TS_LIBRARY_DEFINES_THE_LANGUAGE_2026_10_31.md M3, S5): each a timeseries::line:: function",
                "// of the library, its parameters by place as #TS binds them (TsCatalog), its forms and its description -- what a",
                "// formula box completes and a help page says.",
                "",
                "/** A parameter of a word: its kind (line, line_or_number, members, span, whole, number, word, date, since), what",
                " *  a span takes (observations, period, all, date), an option's words, and whether a call must give it. */",
                "export interface TsWordParam {",
                "  readonly name: string;",
                "  readonly kind: string;",
                "  readonly takes: readonly string[];",
                "  readonly words: readonly string[];",
                "  readonly required: boolean;",
                "}",
                "",
                "/** A word: its parameters by place, its forms (each overload as written), its description, its other",
                " *  spellings (the library's timeseries::Words.alias: mean's avg), and its facts -- the library's other",
                " *  timeseries::Words tags by name (label, family, unit, level, bounds, gsQuant, about, differs, param, search)",
                " *  and its stereotypes (band, candles, anchored): what a drawing and a formula box know of it. */",
                "export interface TsWord {",
                "  readonly params: readonly TsWordParam[];",
                "  readonly forms: readonly string[];",
                "  readonly doc: string | null;",
                "  readonly aliases: readonly string[];",
                "  readonly facts: Readonly<Record<string, readonly string[]>>;",
                "  readonly marks: readonly string[];",
                "}",
                "",
                "/** Every word, by its name. */",
                "export const TS_WORDS: Readonly<Record<string, TsWord>> = {"));
        for (TsCatalog.Word w : words) {
            out.add("  " + w.name() + ": {");
            out.add("    params: [");
            for (TsCatalog.Param p : w.params()) {
                out.add("      { name: " + quote(p.name()) + ", kind: " + quote(p.kind()) + ", takes: " + list(p.takes())
                        + ", words: " + list(p.words()) + ", required: " + p.required() + " },");
            }
            out.add("    ],");
            out.add("    forms: " + list(w.forms()) + ",");
            out.add("    doc: " + (w.doc() == null ? "null" : quote(w.doc())) + ",");
            out.add("    aliases: " + list(w.aliases()) + ",");
            out.add("    facts: {" + w.facts().entrySet().stream().map(e -> " " + e.getKey() + ": " + list(e.getValue()))
                    .collect(Collectors.joining(",")) + (w.facts().isEmpty() ? "}," : " },"));
            out.add("    marks: " + list(w.marks()) + ",");
            out.add("  },");
        }
        out.addAll(List.of("};", ""));
        return String.join("\n", out);
    }

    private static String wordsMd(List<TsCatalog.Word> words) {
        List<String> out = new ArrayList<>(List.of(
                "<!-- GENERATED by core's TsCatalogExport from projects/timeseries/model.pure -- DO NOT EDIT.",
                "     Regenerate: bazel run //docs:update_ts_words. -->",
                "",
                "# The words of `#TS`",
                "",
                "Every word is a `timeseries::line::` function of the timeseries library (`projects/timeseries/model.pure`):",
                "what it computes is its Pure, what follows is read from its overloads as core compiles them. A word's",
                "lines come first; a parameter not required has the library's default. A span is a window or a lag: a number",
                "of observations (`20`), a calendar period (`3mo`), `all` (the line's start to date), or a date on",
                "(`'2024-01-01'`), as the word's forms allow.",
                ""));
        for (TsCatalog.Word w : words) {
            out.add("## `" + w.name() + "`");
            out.add("");
            if (w.doc() != null) {
                out.add(w.doc());
                out.add("");
            }
            if (!w.aliases().isEmpty()) {
                out.add("Also written " + w.aliases().stream().map(a -> "`" + a + "`").collect(Collectors.joining(", "))
                        + ".");
                out.add("");
            }
            out.add("| Parameter | Kind | Takes | Required |");
            out.add("|---|---|---|---|");
            for (TsCatalog.Param p : w.params()) {
                String takes = !p.takes().isEmpty() ? String.join(", ", p.takes())
                        : !p.words().isEmpty() ? String.join(", ", p.words()) : "";
                out.add("| `" + p.name() + "` | " + p.kind() + " | " + takes + " | " + (p.required() ? "yes" : "no")
                        + " |");
            }
            out.add("");
            out.add("Forms: " + w.forms().stream().map(f -> "`" + f + "`").collect(Collectors.joining(", ")) + ".");
            out.add("");
        }
        return String.join("\n", out);
    }
}
