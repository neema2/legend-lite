package com.legend.generators;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * GENERATES {@code com/legend/compiler/CoreImports.java} whole: the engine's {@code CompileContext.META_IMPORTS},
 * in the engine's order (first-match resolution makes order semantic — see {@link CoreImportsParityTest}). It reads
 * CompileContext.java alone, so only an upgrade moves it.
 *
 * <pre>
 *   ImportsGenerator &lt;CompileContext.java&gt; &lt;output&gt;
 * </pre>
 *
 * A build action (spec/BUILD.bazel, :gen_imports); the committed file is kept equal
 * to its output by //core:update_generated and its diff test.
 */
public final class ImportsGenerator {

    private ImportsGenerator() {}

    public static void main(String[] args) throws IOException {
        if (args.length != 2) {
            throw new IllegalArgumentException("usage: ImportsGenerator <CompileContext.java> <output>");
        }
        List<String> imports = metaImports(Files.readString(Path.of(args[0]), StandardCharsets.UTF_8));
        Files.writeString(Path.of(args[1]), render(imports), StandardCharsets.UTF_8);
        System.out.println("[imports] generated " + imports.size() + " packages");
    }

    /** {@code META_IMPORTS}' packages, in order, from CompileContext.java's text. */
    public static List<String> metaImports(String compileContextJava) {
        int at = compileContextJava.indexOf("META_IMPORTS");
        if (at < 0) {
            throw new IllegalStateException("CompileContext.META_IMPORTS not found — upstream moved it");
        }
        int end = compileContextJava.indexOf(");", at);
        Matcher m = Pattern.compile("\"(meta::[A-Za-z0-9_:]+)\"").matcher(compileContextJava.substring(at, end));
        List<String> out = new ArrayList<>();
        while (m.find()) {
            out.add(m.group(1));
        }
        return out;
    }

    /** CoreImports.java's text for {@code imports}, LF on every platform. */
    public static String render(List<String> imports) {
        if (imports.isEmpty()) {
            throw new IllegalStateException("CompileContext.META_IMPORTS named no package — upstream moved it");
        }
        StringBuilder out = new StringBuilder();
        out.append("// GENERATED by //spec:gen_imports from legend-engine's CompileContext.META_IMPORTS -- do not edit.\n")
                .append("// Regenerate: bazel run //:update_generated\n")
                .append("package com.legend.compiler;\n\n")
                .append("import java.util.List;\n\n")
                .append("/**\n")
                .append(" * The implicit import group every element resolves through, walked FIRST-MATCH: the engine's\n")
                .append(" * sequence ({@code CompileContext.META_IMPORTS}: legend-pure's {@code system::imports::coreImport}\n")
                .append(" * plus the packages the engine adds, at the engine's positions). The order is semantic;\n")
                .append(" * {@code CoreImportsParityTest} holds it.\n")
                .append(" */\n")
                .append("public final class CoreImports {\n\n")
                .append("    private CoreImports() {}\n\n")
                .append("    /** The packages, in the engine's order. */\n")
                .append("    public static final List<String> SEQUENCE = List.of(\n");
        for (int k = 0; k < imports.size(); k++) {
            out.append("            \"").append(imports.get(k)).append('"').append(k + 1 < imports.size() ? ",\n" : ");\n");
        }
        return out.append("}\n").toString();
    }
}
