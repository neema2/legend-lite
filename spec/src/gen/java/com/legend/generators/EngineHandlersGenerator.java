package com.legend.generators;

import com.legend.builtin.Prelude;
import com.legend.builtin.Pure;
import com.legend.model.Function;
import com.legend.model.NativeFunctionDefinition;
import com.legend.model.PackageableElement;
import com.legend.model.SignatureMangle;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * GENERATES engine-handlers.tsv — THE ENGINE SURFACE BY BARE NAME, from the
 * pinned engine's own registry (untangle step 4b). Legend-engine resolves a
 * query's function by its bare name against {@code Handlers.java}'s map
 * FIRST, and only then through the import group ({@code
 * CompileContext.resolveFunctionBuilder}); every handler entry names the exact
 * signature ids it stands for ({@code h("<id>", "<name>", ...)}). This table
 * is that map, verbatim from the pinned text — the resolver's bare-name tier
 * has a source, a version and a drift test, never a catalog-wide index.
 *
 * <p>Each id is resolved to its declaration (the catalog's native or the
 * prelude's function of that id) so a row carries the FQN the resolver
 * qualifies to. An id the platform declares nowhere is kept with an empty FQN:
 * the census of engine handlers we do not yet carry (pinned shrink-only).
 *
 * <p>The platform's own product surface ({@link Pure#LITE_SURFACE}) is appended
 * as its declared extension — the engine's {@code
 * getExtraFunctionHandlerDispatchBuilderInfoCollectors} hook, mirrored.
 *
 * <p>Columns: {@code name \t id \t fqn \t source} ({@code engine} or {@code lite}).
 */
public final class EngineHandlersGenerator {

    private EngineHandlersGenerator() {
    }

    /** {@code h("<id>", "<name>"} inside a group, or a direct {@code register("<id>", "<name>", ...)}: the two entry forms. */
    private static final Pattern ENTRY = Pattern.compile("\\b(?:h|register)\\(\\s*\"([^\"]+)\"\\s*,\\s*\"([^\"]+)\"");

    public static void main(String[] args) throws IOException {
        if (args.length != 2) {
            throw new IllegalArgumentException("usage: EngineHandlersGenerator <Handlers.java> <output>");
        }
        String text = generate(Files.readString(Path.of(args[0]), StandardCharsets.UTF_8));
        Files.writeString(Path.of(args[1]), text, StandardCharsets.UTF_8);
        System.out.println("[engine-handlers] generated " + (text.split("\n").length - 2) + " rows");
    }

    /** The engine's (name, id) pairs, in the registry's order, deduplicated. */
    public static Map<String, List<String>> entries(String handlersJava) {
        Map<String, List<String>> byName = new LinkedHashMap<>();
        Matcher m = ENTRY.matcher(handlersJava);
        while (m.find()) {
            List<String> ids = byName.computeIfAbsent(m.group(2), k -> new ArrayList<>());
            if (!ids.contains(m.group(1))) {
                ids.add(m.group(1));
            }
        }
        if (byName.isEmpty()) {
            throw new IllegalStateException("Handlers.java carries no h(\"id\", \"name\") entries — upstream moved them");
        }
        return byName;
    }

    static String generate(String handlersJava) {
        Map<String, Function> declared = new LinkedHashMap<>();
        for (NativeFunctionDefinition n : Pure.all()) {
            declared.put(SignatureMangle.mangle(n), n);
        }
        for (PackageableElement el : Prelude.elements()) {
            if (el instanceof Function f) {
                declared.putIfAbsent(SignatureMangle.mangle(f), f);
            }
        }
        StringBuilder sb = new StringBuilder();
        sb.append("# engine-handlers.tsv — THE ENGINE SURFACE BY BARE NAME: legend-engine's Handlers.java registry")
          .append(" (pinned), each bare name with the signature ids it stands for and the FQN the platform declares")
          .append(" for that id (empty: an engine handler the platform does not carry). 'lite' rows are the")
          .append(" platform's own surface, its declared extension. Generated by EngineHandlersGenerator;")
          .append(" regenerate: bazel run //:update_generated.\n");
        sb.append("name\tid\tfqn\tsource\n");
        int undeclared = 0;
        for (var e : new TreeMap<>(entries(handlersJava)).entrySet()) {
            for (String id : e.getValue()) {
                Function f = declared.get(id);
                if (f == null) {
                    undeclared++;
                }
                sb.append(e.getKey()).append('\t').append(id).append('\t')
                  .append(f == null ? "" : f.qualifiedName()).append("\tengine\n");
            }
        }
        // the platform's own surface: every lite native whose simple name is on
        // the surface list, by the surface name
        for (String name : new TreeSet<>(Pure.LITE_SURFACE)) {
            boolean found = false;
            for (NativeFunctionDefinition n : Pure.all()) {
                if (n.qualifiedName().startsWith(Pure.Lite.PKG)
                        && n.qualifiedName().endsWith("::" + name)) {
                    sb.append(name).append('\t').append(SignatureMangle.mangle(n)).append('\t')
                      .append(n.qualifiedName()).append("\tlite\n");
                    found = true;
                }
            }
            if (!found) {
                throw new IllegalStateException("LITE_SURFACE names '" + name + "' but no lite native has that name");
            }
        }
        System.out.println("[engine-handlers] engine ids the platform does not declare: " + undeclared);
        return sb.toString();
    }
}
