def candidates(c: model.Corpus, seeded: set[str]) -> list[str]:
    """The seed classes, each checked to still be worth re-mapping: seeded, single-table,
    with enough columns to be worth splitting across scope blocks."""
    out = []
    for cls in SEED_CLASSES:
        tbl = c.main_table.get(cls)
        if tbl is None or tbl not in seeded or cls in c.views:
            raise SystemExit(f"dense_mapping seed {cls} is no longer a seeded, mapped class")
        cols = c.columns.get(cls, {})
        table = c.tables.get(tbl)
        # Only columns that really exist on the main table -- a property mapped through a
        # join is not something this generator can restate.
        if (table is None or not table.pk or len(cols) < 4 or _identifier(c, cls) is None
                or not all(col in table.columns for col in cols.values())):
            raise SystemExit(f"dense_mapping seed {cls} no longer qualifies for re-mapping")
        out.append(cls)
    return out


def _db_of(c: model.Corpus, table: str) -> str:
    return getattr(c.tables[table], "database", "store::DB")


def build(c: model.Corpus, seeded: set[str]) -> str:
    """The dense mapping, as .pure text."""
    classes = candidates(c, seeded)
    lines = [HEADER, "###Mapping", "Mapping stress::DenseMapping", "("]

    for n, cls in enumerate(classes):
        tbl = c.main_table[cls]
        table = c.tables[tbl]
        db = _db_of(c, tbl)
        cols = c.columns[cls]
        ident = _identifier(c, cls)
        short = cls.split("::")[-1]

        # Split the property mappings into two scope blocks. One scope would prove the
        # keyword parses; two proves the composer really is flattening them back into one
        # set rather than producing two.
        props = [p for p in sorted(cols) if p != ident]
        half = max(1, len(props) // 2)
        first, second = props[:half], props[half:]

        setid = f"d{n}_{short.lower()}"
        lines.append(f"   *{cls}[{setid}]: Relational")
        lines.append("   {")
        lines.append(f"      ~primaryKey ( [{db}]{tbl}.{table.pk[0]} )")
        lines.append(f"      ~mainTable [{db}]{tbl}")
        lines.append(f"      {ident}: [{db}]{tbl}.{cols[ident]},")
        lines.append(f"      scope([{db}]{tbl})")
        lines.append("      (")
        lines.append(",\n".join(f"         {p}: {cols[p]}" for p in first))
        lines.append("      )" + ("," if second else ""))
        if second:
            # The db-pointer-only form of scope, so BOTH arms of the rule are exercised.
            lines.append(f"      scope([{db}])")
            lines.append("      (")
            lines.append(",\n".join(f"         {p}: {tbl}.{cols[p]}" for p in second))
            lines.append("      )")
        lines.append("   }")
        lines.append("")

    lines.append(")")
    return "\n".join(lines) + "\n"


