"""
Generates a FEATURE-DENSE mapping that is semantically identical to the flat one.

94% of the corpus's 397 class mappings are `~mainTable` plus a list of direct columns. The
features that make a Legend mapping interesting -- scopes, set ids, inheritance, includes,
store substitution -- are absent, so nothing has ever tested them and no finding could have
come from them.

The obstacle to fixing that is the ORACLE. Features that change values -- dynafunctions, join
chains, `~distinct`, `~filter` -- need oracle.py to compute the same thing a different way,
which is real work and a real risk of asserting the generator's opinion rather than the
truth.

So this starts with the half that needs NO oracle change: features that restructure a mapping
without altering what it means.

    scope([db]T)( ... )        purely syntactic grouping; the composer flattens it back
    *Class[id] / Class[id]     set ids and the root marker
    extends [parentId]         property mappings inherited from another set
    ~primaryKey ( ... )        declares what was already implied by the table's PK
    include / substitution     the same mappings, reached through another mapping

Every one of those is a different SPELLING of the flat mapping beside it. That makes the
assertion free and unusually strong: run the same query through both mappings and the results
must be IDENTICAL. No expectation is computed, so no expectation can be wrong -- and the
corpus already has this mechanism, INVARIANCE_GROUPS in battery.py, built for exactly this
shape of claim.

What this deliberately does NOT do is generate a dynafunction or a join chain. Those change
the answer, the oracle cannot yet follow them, and generating them here would produce tests
whose expectations came from the engine being tested. That is phase two, and it is gated on
oracle support rather than on syntax -- the syntax is already verified in
scripts/corpus/verified/.
"""
from __future__ import annotations

import model

HEADER = """// GENERATED by scripts/corpus/dense_mapping.py -- do not edit by hand.
//
// A SECOND mapping of classes already mapped flatly elsewhere, expressing the same thing
// with the features the flat mapping does not use: scope blocks, set ids, extends, an
// explicit ~primaryKey, and an include of the flat mapping it shadows.
//
// Semantically IDENTICAL by construction. That is the assertion: a query answered through
// this mapping must return exactly what the flat mapping returns, so the invariance holds
// with no computed expectation on either side. A divergence is a defect in how one of the
// two spellings is interpreted -- which is precisely the class of defect the corpus has
// never been able to look for, because it only ever had one spelling.
"""


def _identifier(c: model.Corpus, cls: str) -> str | None:
    table = c.tables.get(c.main_table.get(cls, ""))
    if table is None or not table.pk:
        return None
    return next((p for p, col in c.columns.get(cls, {}).items() if col == table.pk[0]), None)


