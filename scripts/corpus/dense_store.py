"""
Generates a Database that flexes the STORE features the corpus has never used.

The model has 184 joins and every one of them is a single-column equality. It has one View,
one Filter, no Schema, no TabularFunction, no MultiGrainFilter, and no join that uses more
than one column or anything other than `=`. That is not a model of a relational store; it is
a model of foreign keys.

This adds a Database that `include`s the existing one and declares new store objects over the
SAME tables. Including rather than duplicating matters: the tables already have seeded rows,
so anything mapped over these objects can actually be executed rather than merely compiled,
and no existing mapping changes meaning because nothing existing is touched.

Everything here is derived from the model -- real tables, real columns, real types -- so a
column rename breaks the generator loudly instead of producing a Database that compiles
against tables that no longer have those columns.

Its join forms were deleted on 2026-10-29: no mapping used them, and the combination matrix
executes each form over data built to satisfy it (see build()).

Every construct's spelling comes from scripts/corpus/verified/store.md, where it was run
through the engine before being written down. Two rules from that survey are load-bearing
here and are easy to get wrong:

  * `and` and `or` have EQUAL precedence and are right-associative, so `A and B or C` parses
    as `A and (B or C)`. Every mixed condition below is parenthesised deliberately.
  * a View's directive order is `~filter` then `~groupBy` then `~distinct` -- the OPPOSITE
    of a class mapping's `~filter ~distinct ~groupBy`. Both are parse errors when wrong.
"""
from __future__ import annotations

import model

DB = "stress::DenseDB"
BASE = "store::DB"

# THE SEED: the tables this generator chooses among. It used to choose among EVERY table in the
# corpus, so adding any stress file whose table sorts first (ACCESS_ENTITLEMENT did) silently
# every object here and churned the file. These are its picks as of the
# file it wrote on 2026-08-14 (6718aae22); widening the store is a deliberate edit to this list.
SEED_TABLES = ("ACCOUNT", "ACCOUNTING_RULE", "ACCRUAL_ENTRY", "ACCRUAL_SCHEDULE")


def _seed(c: model.Corpus) -> list[str]:
    missing = [t for t in SEED_TABLES if t not in c.tables or t in c.views]
    if missing:
        raise SystemExit(f"dense_store seed tables no longer in the model: {missing}")
    return sorted(SEED_TABLES)


def _tables_with(c: model.Corpus, kind: str, minimum: int = 1) -> list[str]:
    """Seed tables having at least `minimum` columns of `kind`, deterministically ordered."""
    out = []
    for name in _seed(c):
        t = c.tables[name]
        if sum(1 for col in t.columns.values() if col.kind == kind) >= minimum:
            out.append(name)
    return out


def _cols(c: model.Corpus, table: str, kind: str) -> list[str]:
    return sorted(col.name for col in c.tables[table].columns.values() if col.kind == kind)


def build(c: model.Corpus) -> str:
    L = [
        "// GENERATED by scripts/corpus/dense_store.py -- do not edit by hand.",
        "//",
        "// Store features the base Database does not use. It INCLUDES store::DB rather than",
        "// redeclaring anything, so these objects sit over tables that already carry seeded",
        "// rows -- executable, not merely compilable -- and no existing mapping is touched.",
        "//",
        "// Spellings verified in scripts/corpus/verified/store.md. Two rules matter here:",
        "// `and`/`or` are equal-precedence and right-associative (so mixed conditions are",
        "// parenthesised), and a View orders its directives ~filter ~groupBy ~distinct --",
        "// the opposite of a class mapping. Both are parse errors when wrong.",
        "",
        "###Relational",
        f"Database {DB}",
        "(",
        f"   include {BASE}",
        "",
    ]

    # ---- a Schema, with its own tables and a view over them ------------------------------
    L += [
        "   // A Schema, so a schema-qualified table reference is resolved somewhere in the corpus",
        "   // (the base model's tables sit in the default schema).",
        "   Schema analytics",
        "   (",
        "      Table DESK_SUMMARY",
        "      (",
        "         DESK_ID VARCHAR(64) PRIMARY KEY,",
        "         AS_OF DATE PRIMARY KEY,",
        "         HEADCOUNT INTEGER,",
        "         GROSS_NOTIONAL DOUBLE,",
        "         LABEL VARCHAR(128)",
        "      )",
        "      Table DESK_LIMIT",
        "      (",
        "         DESK_ID VARCHAR(64) PRIMARY KEY,",
        "         LIMIT_KIND VARCHAR(32) PRIMARY KEY,",
        "         LIMIT_VALUE DOUBLE NOT NULL",
        "      )",
        "      // A TabularFunction: its parenthesised body is a COLUMN SCHEMA, not an",
        "      // argument list -- the same columnDefinition rule a Table uses.",
        "      TabularFunction DESK_ROLLUP",
        "      (",
        "         DESK_ID VARCHAR(64) NOT NULL,",
        "         TOTAL DOUBLE",
        "      )",
        "   )",
        "",
    ]

    # The JOIN forms this generator wrote -- multi-column, non-equality, `or` mixed with null tests, a dynafunction on
    # one side and on both, a {target} self-join -- were deleted 2026-10-29 (the improvement plan's Phase 7, the user's
    # decision). No mapping used one, and each repeats a form the combination matrix (combos.py: Combo_Multi,
    # Combo_Ineq, Combo_Or, Combo_Dyna1, Combo_Dyna2; the self-joins Pillar_LongerPillar and Trader_Manager) executes
    # over data derived to satisfy it, where over these tables the dynafunction pair matched no rows at all.
    # The view and the filters below still root at the tables the joins were drawn from.
    num = _tables_with(c, "float", 1) or _tables_with(c, "int", 1)
    strt = _tables_with(c, "string", 2)
    L += [""]

    # ---- filters -------------------------------------------------------------------------
    # The view's root: the table its ~groupBy and columns read.
    root = num[0] if num and strt else None
    view_filter = "dense_NotNull"
    if strt:
        t = strt[0]
        s1 = _cols(c, t, "string")[0]
        L += [f"   Filter dense_NotNull({t}.{s1} is not null)"]
        # RULE (hand fix d0367624b, 2026-09-22): a view's ~filter must read the view's own
        # root. A filter over a table the view never reads compiles in the engine and fails at
        # SQL generation; this platform refuses it at build. So when dense_NotNull reads
        # another table, the view gets its own NotNull filter over its root's primary key.
        if root and root != t:
            view_filter = f"dense_{root.split('_')[0].title()}NotNull"
            L += [
                "   // A view's ~filter must read the view's own root (or a table its joins",
                "   // reach): the engine compiles a filter over an unrelated table and fails",
                "   // at SQL generation; this platform refuses it at build (views are lifted",
                f"   // eagerly, strict entry — 2026-09-22). dense_Rollup roots at {root}.",
                f"   Filter {view_filter}({root}.{c.tables[root].pk[0]} is not null)",
            ]
        L += [
            "   // A MultiGrainFilter is referenced from a mapping exactly like a Filter;",
            "   // the distinction is consumed by the planner for join elision.",
            f"   MultiGrainFilter dense_Grain({t}.{s1} is not null)",
            "",
        ]

    # ---- views: all three directives, in the VIEW's order --------------------------------
    if num and strt:
        t = num[0]
        f1 = (_cols(c, t, "float") or _cols(c, t, "int"))[0]
        pk = c.tables[t].pk[0]
        L += [
            "   // Directive order here is ~filter, ~groupBy, ~distinct. A class mapping",
            "   // orders the last two the other way round.",
            "   View dense_Rollup",
            "   (",
            f"      ~filter {view_filter}",
            "      ~groupBy",
            "      (",
            f"         {t}.{pk}",
            "      )",
            "      ~distinct",
            f"      key: {t}.{pk} PRIMARY KEY,",
            f"      total: sum({t}.{f1})",
            "   )",
            "",
        ]

    L += [")", ""]
    return "\n".join(L)


if __name__ == "__main__":
    c = model.load()
    text = build(c)
    print(f"dense store: {len(text.splitlines())} lines")
    for k in ("Schema", "TabularFunction", "MultiGrainFilter", "Filter ", "View ", "Join "):
        print(f"  {k:<18}{text.count(k)}")
