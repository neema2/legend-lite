"""
The trader features, as services over the one trading model (docs/DEEPHAVEN_TRADER_DEMOS_2026_10_24.md DH34, §6).

Every other generator here walks the MODEL -- its classes, its associations, its mapping features -- and asks the
queries a model invites. A trader's screen asks different ones: a computed column (a price rounded to a tick, a
quantity as text), a statistic per name (a VWAP, a spread of prices, a correlation), a moving figure (a running volume,
a three-print average, a rank within a book), a candle, and the prevailing quote at a trade's instant. Those are the
features the Deephaven target is built feature by feature against (§2: K1, K3a, K6, K7 and the scalars and aggregates
beside them), so each is a service here, over the hand-written trades (seed.py) and the market's hand-written day
(tape.py), every expectation the oracle's.

Grouped by feature FAMILY, one family per service, so a target that lacks one fails that service and no other -- a
failure names the feature. Each window, aggregate and frame is evaluated by oracle.py from SQL's stated semantics; a
query whose answer an order would decide (a tie in a window's order, two quotes at the winning instant) is refused by the
oracle, and the queries below are written so that none is.

Not here, with the reason: an exponential moving average and a tick-to-tick delta (no Pure function names either);
`now()`-relative windows (the corpus never reads the clock -- they are a fixed instant here, and the live ones are tested
on the live tape); `joinStrings` per group (the concatenation's order is the database's).
"""
from __future__ import annotations

import query
from query import AsOf, DateTimeArg, Pred, Proj, Spec, Window

TRADE = "trading::Trade"
PRINT = "marketdata::MarketTrade"
QUOTE = "marketdata::MarketQuote"

# The market's day: the tape's rows and none of the expansion ring's (whose prints are months apart).
DAY = [Pred(["printTime"], ">=", DateTimeArg("2024-06-03 00:00:00")),
       Pred(["printTime"], "<", DateTimeArg("2024-06-06 00:00:00"))]
MINUTES = "MINUTES"
DURATION = "meta::pure::functions::date::DurationUnit"
# A statistic to the six places a screen shows: Number narrowed to Float, then Pure's round with a scale.
_SIX = "->cast(@Float)->round(6)"


def _spec(name: str, doc: str, root: str) -> Spec:
    return Spec(f"stress::TF_{name}", f"/stress/tf_{name.lower()}",
                doc + " Generated by scripts/corpus/features.py.", root)


def _p(alias: str, path: str | None = None) -> Proj:
    return Proj(alias, (path or alias).split("."))


def _x(alias: str, expr: str, kind: str) -> Proj:
    return Proj(alias, [], expr=expr, kind=kind)


def _trade_columns() -> list[Proj]:
    return [_p("tradeId"), _p("instrumentId", "instrument.instrumentId"), _p("bookId", "book.bookId"),
            _p("createdTime"), _p("quantity"), _p("price"), _p("notional")]


def scalars() -> list[Spec]:
    s = _spec("TradeScalars",
              "A blotter's computed columns over the booked trades: a price converted at a fixed rate and rounded to "
              "the cent, the shares beyond whole lots of a thousand, the trade type's three-letter code, whether the "
              "status reads as an execution, and the quantity as text -- Pure's round with a scale, mod, substring (zero-based, "
              "the end exclusive: Java's contract), contains and toString.", TRADE)
    s.projections = [_p("tradeId"),
                     _x("priceEur", "round($x.price * 0.9213, 2)", "float"),
                     _x("oddLot", "mod(round($x.quantity), 1000)", "int"),
                     _x("typeCode", "substring($x.tradeType, 0, 3)", "string"),
                     _x("isExecution", "contains($x.status, 'EXEC')", "bool"),
                     _x("quantityText", "toString(round($x.quantity))", "string")]
    s.sort = ("tradeId", False)
    p = _spec("PrintScalars",
              "Time and sales' computed columns over the market's day: the print's value, its price in ticks of a "
              "twentieth, its sequence as text, and its venue's first two letters.", PRINT)
    p.projections = [_p("printId"),
                     _x("value", "$x.price * $x.quantity", "float"),
                     _x("ticks", "round($x.price * 20.0)", "int"),
                     _x("sequenceText", "toString($x.sequenceNumber)", "string"),
                     _x("venueHead", "substring($x.venue, 0, 2)", "string")]
    p.filters = list(DAY)
    p.sort = ("printId", False)
    return [s, p]


def aggregates() -> list[Spec]:
    out = []
    # minBy/maxBy take a NUMERIC key (RowMapper<T, Number>): a trade's instant as epoch seconds
    base = [_p("tradeId"), _p("instrumentId", "instrument.instrumentId"),
            _x("epoch", "toEpochValue($x.createdTime)", "int"), _p("quantity"), _p("price"), _p("notional"),
            _p("executionVenue"), _p("bookId", "book.bookId")]
    for name, doc, aggs in [
        ("InstrumentVwap",
         "A watchlist's figures per name over the booked trades: the trades, the volume, the volume-weighted average "
         "price, and the first and last prices by time -- Pure's wavg, and minBy/maxBy over a rowMapper keyed by "
         "the trade's epoch seconds (toEpochValue).",
         [("trades", "tradeId", "count"), ("volume", "quantity", "sum"),
          ("vwap", ("price", "quantity"), "wavg"),
          ("firstPrice", ("price", "epoch"), "minBy"), ("lastPrice", ("price", "epoch"), "maxBy")]),
        ("InstrumentDispersion",
         "The spread of each name's trade prices, to the precision a screen shows (a statistic is approximate in "
         "every database -- a streaming variance over three gilt prices within 0.0075 of each other is 178 units in "
         "the last place from the exact one -- so the service asks for six places, as a risk screen would): the "
         "sample and population standard deviations and variances, the median, and the ninetieth percentile of "
         "notional (continuous: interpolated between neighbours) to the cent.",
         [("pxStdDev", "price", f"stdDevSample(){_SIX}"), ("pxStdDevPop", "price", f"stdDevPopulation(){_SIX}"),
          ("pxVar", "price", f"varianceSample(){_SIX}"), ("pxVarPop", "price", f"variancePopulation(){_SIX}"),
          ("pxMedian", "price", "median"),
          ("notionalP90", "notional", "percentile(0.9)->toOne()->cast(@Float)->round(2)")]),
        ("InstrumentCorrelation",
         "Whether size moves with price, per name, to six places: Pure's corr and the sample and population "
         "covariances of a trade's price and its quantity (each Number[0..1], so made one Float to be rounded).",
         [("pxQtyCorr", ("price", "quantity"), f"corr()->toOne(){_SIX}"),
          ("pxQtyCovar", ("price", "quantity"), f"covarSample()->toOne(){_SIX}"),
          ("pxQtyCovarPop", ("price", "quantity"), f"covarPopulation()->toOne(){_SIX}")]),
        ("InstrumentMix",
         "How each name traded: the distinct venues it executed on and the distinct books it was booked in.",
         [("venues", "executionVenue", "distinct()->count()"), ("books", "bookId", "distinct()->count()")]),
    ]:
        s = _spec(name, doc, TRADE)
        s.projections = list(base)
        s.group_by = ["instrumentId"]
        s.aggs = aggs
        s.sort = ("instrumentId", False)
        out.append(s)
    return out


def windows() -> list[Spec]:
    out = []
    over_time = dict(partition=["instrumentId"], order=[("createdTime", False)])
    s = _spec("TradeRunning",
              "Each name's trades in time order with its running figures (SQL's default frame: the start to the current "
              "row): the running volume and notional, the trade's number, the prices before and after it, and the "
              "first price so far.", TRADE)
    s.projections = _trade_columns()
    s.windows = [Window("cumQty", "sum", "quantity", **over_time),
                 Window("cumNotional", "sum", "notional", **over_time),
                 Window("tradeNo", "rowNumber", **over_time),
                 Window("prevPrice", "lag", "price", **over_time),
                 Window("nextPrice", "lead", "price", **over_time),
                 Window("twoBack", "lag", "price", args=[2], **over_time),
                 Window("openPrice", "first", "price", **over_time)]
    s.sort = ("tradeId", False)
    out.append(s)

    m = _spec("TradeMoving",
              "Moving figures over each name's last three trades (rows(-2, 0)) and a centred volume (rows(-1, 1)).",
              TRADE)
    m.projections = _trade_columns()
    m.windows = [Window("ma3", "average", "price", frame=("rows", -2, 0), **over_time),
                 Window("hi3", "max", "price", frame=("rows", -2, 0), **over_time),
                 Window("lo3", "min", "price", frame=("rows", -2, 0), **over_time),
                 Window("n3", "count", "price", frame=("rows", -2, 0), **over_time),
                 Window("qtyAround", "sum", "quantity", frame=("rows", -1, 1), **over_time)]
    m.sort = ("tradeId", False)
    out.append(m)

    r = _spec("TradeRanks",
              "Each trade's place in its book by notional, largest first: rank and denseRank (three trades tie at "
              "250,000), percentRank and cumulativeDistribution, and over a tie-free order its row number and tercile.",
              TRADE)
    r.projections = _trade_columns()
    by_size = dict(partition=["bookId"], order=[("notional", True)])
    tie_free = dict(partition=["bookId"], order=[("notional", True), ("tradeId", False)])
    r.windows = [Window("rank", "rank", **by_size), Window("denseRank", "denseRank", **by_size),
                 Window("pctRank", "percentRank", **by_size), Window("cumeDist", "cumulativeDistribution", **by_size),
                 Window("place", "rowNumber", **tie_free), Window("tercile", "ntile", args=[3], **tie_free)]
    r.sort = ("tradeId", False)
    out.append(r)

    t = _spec("TradeTopTwo",
              "Each name's two largest trades: a row number over the name by notional, kept where it is at most two "
              "(SQL's QUALIFY).", TRADE)
    t.projections = _trade_columns()
    t.windows = [Window("place", "rowNumber", partition=["instrumentId"],
                        order=[("notional", True), ("tradeId", False)])]
    t.post_filters = [Pred(["place"], "<=", 2)]
    t.sort = [("instrumentId", False), ("place", False)]
    out.append(t)

    w = _spec("TradeBookTotals",
              "Each trade beside its book's whole: the book's notional and its trades, an unordered window over the "
              "partition.", TRADE)
    w.projections = _trade_columns()
    w.windows = [Window("bookNotional", "sum", "notional", partition=["bookId"]),
                 Window("bookTrades", "count", "tradeId", partition=["bookId"]),
                 Window("bookLargest", "max", "notional", partition=["bookId"])]
    w.sort = ("tradeId", False)
    out.append(w)

    q = _spec("TradeLastFifteenMinutes",
              "Each name's volume and trades in the fifteen minutes up to each trade: a time range frame "
              "(_range(-15, MINUTES, 0, MINUTES)).", TRADE)
    q.projections = _trade_columns()
    q.windows = [Window("qty15m", "sum", "quantity", frame=("range", -15, 0, MINUTES), **over_time),
                 Window("trades15m", "count", "tradeId", frame=("range", -15, 0, MINUTES), **over_time)]
    q.sort = ("tradeId", False)
    out.append(q)
    return out


def _print_columns() -> list[Proj]:
    return [_p("printId"), _p("instrumentId", "instrument.instrumentId"), _p("sequenceNumber"), _p("printTime"),
            _p("price"), _p("quantity")]


def tape() -> list[Spec]:
    out = []
    by_seq = dict(partition=["instrumentId"], order=[("sequenceNumber", False)])
    s = _spec("TapeTimeAndSales",
              "Time and sales over the market's day: each print with its name's running volume, the price it ticked "
              "from (an uptick or a downtick on the screen) and the running high and low.", PRINT)
    s.projections = _print_columns()
    s.filters = list(DAY)
    s.windows = [Window("dayVolume", "sum", "quantity", **by_seq),
                 Window("tickFrom", "lag", "price", **by_seq),
                 Window("dayHigh", "max", "price", **by_seq),
                 Window("dayLow", "min", "price", **by_seq)]
    s.sort = ("printId", False)
    out.append(s)

    e = _spec("TapeEma",
              "A chart's technical lines over the market's day: each name's fast and slow exponential moving averages of "
              "its price (lite's ema, alpha 0.5 and 0.2) and of its print size, over the running frame by sequence -- "
              "the first value, then alpha * value + (1 - alpha) * so far, a NULL skipped.", PRINT)
    e.projections = _print_columns()
    e.filters = list(DAY)
    running = dict(by_seq, frame=("rows", None, 0))
    e.windows = [Window("emaFast", "ema", "price", args=[0.5], **running),
                 Window("emaSlow", "ema", "price", args=[0.2], **running),
                 Window("emaSize", "ema", "quantity", args=[0.2], **running)]
    e.sort = ("printId", False)
    out.append(e)

    r = _spec("TapeRollingFiveMinutes",
              "The last five minutes at each print (a time range frame over the print time; two prints share an "
              "instant, so the frame holds its peers): volume, high, low and prints.", PRINT)
    r.projections = _print_columns()
    r.filters = list(DAY)
    five = dict(partition=["instrumentId"], order=[("printTime", False)], frame=("range", -5, 0, MINUTES))
    r.windows = [Window("vol5m", "sum", "quantity", **five), Window("hi5m", "max", "price", **five),
                 Window("lo5m", "min", "price", **five), Window("prints5m", "count", "printId", **five)]
    r.sort = ("printId", False)
    out.append(r)

    c = _spec("TapeCandles",
              "Five-minute candles over the market's day: open and close by sequence (minBy and maxBy), high, low, "
              "volume, VWAP and prints, per name and bucket (timeBucket).", PRINT)
    c.projections = [_p("instrumentId", "instrument.instrumentId"),
                     _x("bucket", f"timeBucket($x.printTime, 5, {DURATION}.MINUTES)", "timestamp"),
                     _p("sequenceNumber"), _p("price"), _p("quantity")]
    c.filters = list(DAY)
    c.group_by = ["instrumentId", "bucket"]
    c.aggs = [("open", ("price", "sequenceNumber"), "minBy"), ("close", ("price", "sequenceNumber"), "maxBy"),
              ("high", "price", "max"), ("low", "price", "min"), ("volume", "quantity", "sum"),
              ("vwap", ("price", "quantity"), "wavg"), ("prints", "price", "count")]
    c.sort = [("instrumentId", False), ("bucket", False)]
    out.append(c)

    f = _spec("TapeFifteenMinutesToTen",
              "Each name's prints between 09:35 and 09:50 on the 3rd, a fixed clock: volume, VWAP, high, low.", PRINT)
    f.projections = [_p("instrumentId", "instrument.instrumentId"), _p("price"), _p("quantity")]
    f.filters = [Pred(["printTime"], ">=", DateTimeArg("2024-06-03 09:35:00")),
                 Pred(["printTime"], "<", DateTimeArg("2024-06-03 09:50:00"))]
    f.group_by = ["instrumentId"]
    f.aggs = [("volume", "quantity", "sum"), ("vwap", ("price", "quantity"), "wavg"),
              ("high", "price", "max"), ("low", "price", "min")]
    f.sort = ("instrumentId", False)
    out.append(f)

    lots = _spec("TapeLotSizes",
                 "The commonest print size by aggressor side on the lit venues (Pure's mode over Float; neither "
                 "side's is tied), with the side's distinct venues and its prints.", PRINT)
    lots.projections = [_p("aggressorSide"), _p("quantity"), _p("venue"), _p("printId")]
    lots.filters = list(DAY) + [Pred(["isOffExchange"], "not", None)]
    lots.group_by = ["aggressorSide"]
    lots.aggs = [("usualSize", "quantity", "mode"), ("venues", "venue", "distinct()->count()"),
                 ("prints", "printId", "count")]
    lots.sort = ("aggressorSide", False)
    out.append(lots)

    v = _spec("TapeVenueShare",
              "Each name's volume by venue over the market's day, with its off-exchange prints among them.", PRINT)
    v.projections = [_p("instrumentId", "instrument.instrumentId"), _p("venue"), _p("quantity"), _p("printId")]
    v.filters = list(DAY)
    v.group_by = ["instrumentId", "venue"]
    v.aggs = [("volume", "quantity", "sum"), ("prints", "printId", "count")]
    v.sort = [("instrumentId", False), ("venue", False)]
    out.append(v)
    return out


def _quotes(name: str) -> Spec:
    q = _spec(name, "The quotes an as-of join reads.", QUOTE)
    q.projections = [_p("quoteId"), _p("quoteInstrument", "instrument.instrumentId"), _p("quoteTime"), _p("bid"),
                     _p("ask"), _p("mid")]
    return q


def asof() -> list[Spec]:
    out = []
    p = _spec("TapePrevailingQuote",
              "Each print beside the quote prevailing at its instant: an as-of join on the name, the latest quote at "
              "or before the print (one print precedes every quote, two land on a quote's instant).", PRINT)
    p.projections = [_p("printId"), _p("printInstrument", "instrument.instrumentId"), _p("printTime"), _p("price"),
                     _p("quantity")]
    p.filters = list(DAY)
    p.asof = AsOf(_quotes("TapePrevailingQuoteQuotes"), "printTime", ">=", "quoteTime",
                  "printInstrument", "quoteInstrument")
    p.sort = ("printId", False)
    out.append(p)

    n = _spec("TapeNextQuote",
              "Each print beside the first quote AFTER it (strictly): the as-of join's other direction, what a markout "
              "reads.", PRINT)
    n.projections = list(p.projections)
    n.filters = list(DAY)
    n.asof = AsOf(_quotes("TapeNextQuoteQuotes"), "printTime", "<", "quoteTime", "printInstrument", "quoteInstrument")
    n.sort = ("printId", False)
    out.append(n)

    t = _spec("TradePrevailingQuote",
              "Transaction cost: each booked trade beside the market's quote strictly before it, and its price's "
              "distance from that quote's mid in basis points (none where the name has no quote before the trade).",
              TRADE)
    t.projections = [_p("tradeId"), _p("tradeInstrument", "instrument.instrumentId"), _p("createdTime"),
                     _p("price"), _p("quantity")]
    t.asof = AsOf(_quotes("TradePrevailingQuoteQuotes"), "createdTime", ">", "quoteTime",
                  "tradeInstrument", "quoteInstrument")
    t.extends = [("slippageBps", "($x.price - $x.mid) * 10000.0 / $x.mid", "float")]
    t.sort = ("tradeId", False)
    out.append(t)
    return out


def build() -> list[Spec]:
    return scalars() + aggregates() + windows() + tape() + asof()


if __name__ == "__main__":
    import json

    import flat
    import model
    import oracle

    c = model.load()
    tables = flat.all_tables(c)
    for s in build():
        try:
            rows = oracle.as_json_rows(c, s, oracle.evaluate(c, s, tables))
            print(f"== {s.short}: {len(rows)} rows")
            for r in rows[:40]:
                print("  ", json.dumps(r))
        except (oracle.Unsupported, oracle.Fanout) as e:
            print(f"== {s.short}: REFUSED {e}")
