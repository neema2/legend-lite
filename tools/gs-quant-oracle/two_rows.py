"""THE TWO-ROWS TABLE (README.md, "On a line with two rows for one date"): what gs-quant answers over the adversarial
fixture's line with two rows on one date (its duplicate_row trap: BTCUSD's print and its correction on 2025-02-05),
case by case, read from ledger-adversarial-raw.tsv alone -- never typed.

  two_rows.py --ledger ledger-adversarial-raw.tsv --tsv two-rows.tsv --md TWO_ROWS.md

two-rows.tsv is the table's data, diff-tested (//tools/gs-quant-oracle:update_generated_tests, in //:generated, the
checks lane); TWO_ROWS.md is its page, written by the same rule and not diff-tested (prose is never a test input, G17,
as docs/timeseries/WORDS.md). Regenerate both: bazel run //tools/gs-quant-oracle:update_generated.
"""

import argparse
import re
import sys

SYMBOL, DATE = "BTCUSD", "2025-02-05"

# each group: its key, what gs-quant answers, and how a ledger row is told to be in it
GROUPS = (
    ("raises-497", "raises `MqValueError: multiple data points on same date` at `econometrics.py:497`"
                   " (`_get_annualization_factor`)"),
    ("raises-two-rows", "raises elsewhere, because of the two rows (no other symbol raises there)"),
    ("two-values", "answers two values on " + DATE),
    ("four-values", "answers four values on " + DATE + " (the line met with itself or its own window: the two rows"
                    " against the two, 2 x 2)"),
    ("one-or-none", "answers one value, or none, there"),
    ("raises-every-symbol", "raises on every symbol, the two rows aside (gs-quant's calendar-window comparison: a"
                            " gs-quant defect)"),
)


def read(path):
    rows = {}
    names = None
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if line.startswith("#") or not line:
            continue
        cells = line.split("\t")
        if names is None:
            names = cells
            continue
        rows[cells[0]] = dict(zip(names, cells))
    return rows


def classify(rows):
    """Each case run over the two-row line, (case, group, what it answers): every OK or GS_ERROR row at @BTCUSD, in
    the ledger's order; a count of values on the date the table has no group for is refused."""
    raised_on = {}
    for key, r in rows.items():
        if r["gsquant"] == "GS_ERROR" and " @" in key:
            case, symbol = key.rsplit(" @", 1)
            raised_on.setdefault(case, set()).add(symbol)
    symbols = {k.rsplit(" @", 1)[1] for k in rows if " @" in k}
    out = []
    for key, r in rows.items():
        if not key.endswith(" @" + SYMBOL) or r["gsquant"] == "SKIP":
            continue
        case = key[: -len(" @" + SYMBOL)]
        why = r["why"].split(" | lite: ")[0]   # gs-quant's half (the parity test writes the other)
        if r["gsquant"] == "GS_ERROR":
            frame = re.search(r"\(([\w/.]+\.py:\d+)\)$", why)
            where = frame.group(1) if frame else "-"
            if where == "econometrics.py:497":
                group = "raises-497"
            elif raised_on[case] == symbols:
                group = "raises-every-symbol"
            else:
                group = "raises-two-rows"
            out.append((case, group, why.split(":")[0] + " at " + where, r["duckdb"]))
            continue
        count = re.search(r", (\d+) values on " + DATE, why)
        if count is None:
            out.append((case, "one-or-none", why, r["duckdb"]))
        elif count.group(1) == "2":
            out.append((case, "two-values", why, r["duckdb"]))
        elif count.group(1) == "4":
            out.append((case, "four-values", why, r["duckdb"]))
        else:
            raise SystemExit("two_rows.py: " + case + " answers " + count.group(1) + " values on " + DATE
                             + ", a count the table has no group for")
    return out


def tsv(cases):
    lines = ["# THE TWO-ROWS TABLE's data (two_rows.py, from ledger-adversarial-raw.tsv): each case run over " + SYMBOL
             + ", its group and gs-quant's answer there. GENERATED -- regenerate: bazel run"
             " //tools/gs-quant-oracle:update_generated", "case\tgroup\tgs-quant\tlite (duckdb)"]
    lines += [c + "\t" + g + "\t" + a + "\t" + v for c, g, a, v in cases]
    return "\n".join(lines) + "\n"


def md(cases):
    by = {g: [] for g, _ in GROUPS}
    verdicts = {g: {} for g, _ in GROUPS}
    for c, g, _, v in cases:
        by[g].append(c)
        verdicts[g][v] = verdicts[g].get(v, 0) + 1
    out = ["<!-- GENERATED by two_rows.py from ledger-adversarial-raw.tsv -- DO NOT EDIT. Regenerate: bazel run"
           " //tools/gs-quant-oracle:update_generated -->", "",
           "# On a line with two rows for one date", "",
           "The adversarial fixture's `duplicate_row` trap gives " + SYMBOL + " two rows on " + DATE + " (a print and"
           " its correction, `seq` 1929 and 1930). gs-quant is handed both, in `seq` order, and counts by position."
           " Of the mapped cases run over " + SYMBOL + " (`ledger-adversarial-raw.tsv`, rows ` @" + SYMBOL + "`; each"
           " row's `why` says it -- `2 values on " + DATE + "`, or the frame gs-quant raised in):", "",
           "| gs-quant's answer on " + SYMBOL + " " + DATE + " | cases | lite on DuckDB | words (their cases) |",
           "|---|---|---|---|"]
    for g, text in GROUPS:
        words = {}
        for c in by[g]:
            word, args = c.split(" ", 1)
            words.setdefault(word, []).append(args)
        cell = "; ".join("`" + w + "` (" + ", ".join("`" + a + "`" for a in a_) + ")" for w, a_ in words.items())
        lite = ", ".join(str(n) + " " + v for v, n in sorted(verdicts[g].items())) or "-"
        out.append("| " + text + " | " + str(len(by[g])) + " | " + lite + " | " + (cell or "-") + " |")
    out += ["", "lite's REFUSED is register S149's refusal: a word that reads its line in order, met with two rows on one"
                " date, is refused while the query runs, naming the fix (BY or a subscript, or SAMPLE BY 1d with last(x))."
                " A dup-span PASS is today's agreement over both rows, not a vouch for it.",
            "", "Duplicates do not just double-count: where a word aligns the line with itself or with its own window,"
                " the two rows meet the two and gs-quant answers four values on the date (`four-values` above).", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ledger", required=True)
    ap.add_argument("--tsv", required=True)
    ap.add_argument("--md", required=True)
    a = ap.parse_args()
    cases = classify(read(a.ledger))
    with open(a.tsv, "w", encoding="utf-8", newline="\n") as f:
        f.write(tsv(cases))
    with open(a.md, "w", encoding="utf-8", newline="\n") as f:
        f.write(md(cases))
    return 0


if __name__ == "__main__":
    sys.exit(main())
