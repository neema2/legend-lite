"""THE one reader of a column's type in Python, as ``engine-client/src/types.ts`` is DataCube's (docs/
PYTHON_ASKS_DATACUBE_2026_10_15.md, item 4). A column's type is the compiler's: legend-lite's plain name (``Integer``),
or legend-engine's precise primitive by path (``meta::pure::precisePrimitives::BigInt``). What Python
needs from it -- its plain primitive -- is legend-lite's own lattice, generated by running it (``_type_facts.py``, the
table DataCube reads), never its spelling: a name the table does not know is an ERROR, never a guess, because a column
read as the wrong type converts and shows wrongly without a word. No other module names a type to decide what it is: it
asks these (held so by test_frames' ``TypeNamesAreReadHere``, as DataCube's guardrails test holds types.ts). On Python's
standard library alone (the compiler-only install)."""

from __future__ import annotations

from ._type_facts import TYPE_FACTS


class UnknownType(ValueError):
    """A type name legend-lite's lattice does not know: a column typed so is refused, never read as a guess."""


def plain_type(name: str) -> str:
    """The plain Pure primitive a reported type is (``meta::pure::precisePrimitives::Int`` is ``Integer``); an unknown
    name is refused (types.ts ``plainType``)."""
    fact = TYPE_FACTS.get(name)
    if fact is None:
        raise UnknownType(f"the compiler typed a column '{name}', which legend-lite does not read")
    return fact[0]


def is_integer(name: str) -> bool:
    """An Integer, by either compiler's name for one (``precisePrimitives::BigInt`` too)."""
    return plain_type(name) == 'Integer'


def is_float(name: str) -> bool:
    """A Float (a precise ``Double`` too)."""
    return plain_type(name) == 'Float'


def is_decimal(name: str) -> bool:
    """A Decimal (a precise ``Numeric`` too)."""
    return plain_type(name) == 'Decimal'


def is_number(name: str) -> bool:
    """A Number: what a reducer over numbers of more than one kind answers (an Integer's quartile, its deviation), each
    value as the database gave it -- a whole number, a double, or an exact decimal, which arrives as its text, as a
    Decimal's does."""
    return plain_type(name) == 'Number'


def is_boolean(name: str) -> bool:
    """A Boolean."""
    return plain_type(name) == 'Boolean'
