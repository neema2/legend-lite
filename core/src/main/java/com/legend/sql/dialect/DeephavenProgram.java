package com.legend.sql.dialect;

import com.legend.sql.DialectCapability;

import java.util.List;
import java.util.regex.Pattern;

/**
 * A DEEPHAVEN SERVER'S STARTUP PROGRAM, RENDERED (docs/DESK_DATA_ROADMAP_2026_10_29.md B2; the execution tenet's
 * decision rule: engine-exact text is a render target of the one compiler, never strings assembled where they are
 * used): each landing table a stream makes, as a Kafka subscription the server runs at start -- Groovy, as Deephaven's
 * application mode runs it. The planner hands it the subscriptions (each from the model: the dataset's topic, its
 * brokers, its columns with the Java types a Deephaven column holds them as, its key, its retention); this writes them.
 *
 * <p>Each table is read from its topic's beginning by Deephaven's own reader ({@code KafkaTools.consumeToTable}), its
 * records' JSON by the table's columns -- a day read as its text and made a {@code LocalDate} on the server (the JSON
 * reader takes no LocalDate: B1's measurement, 2026-10-30) -- then kept as its dataset lands: an appended table its
 * latest n rows ({@code TableType.ring(n)}) or all of them ({@code append}); a table latest by key each key's last row
 * ({@code TableType.blink()} then {@code lastBy}, measured 2026-10-30, the roadmap's §2 P). The table is then the
 * declared columns alone, in their order, published under its name -- what a plan reads it by (DH18), and what DH16
 * checks. A retention over a time, an Avro topic and a name Groovy cannot hold are refused by name.
 */
public final class DeephavenProgram {

    private DeephavenProgram() {
    }

    /** A column of a subscription's table: its name and the Java type a Deephaven column holds it as (DH16's). */
    public record Column(String name, String type) {
    }

    /** One landing table: its name, its topic, the topic's brokers and format, its columns, the key it keeps each
     *  latest row of (empty: appended), and an appended table's retention -- its latest {@code keepRows} rows, or those
     *  of the last {@code keepFor} -- null for none. */
    public record Subscription(String table, String topic, String bootstrapServers, String format, List<Column> columns,
            List<String> key, @com.legend.base.Nullable Long keepRows, @com.legend.base.Nullable String keepFor) {
        public Subscription {
            columns = List.copyOf(columns);
            key = List.copyOf(key);
        }
    }

    private static final Pattern IDENTIFIER = Pattern.compile("[A-Za-z_][A-Za-z0-9_]*");
    private static final Pattern TOPIC = Pattern.compile("[A-Za-z0-9._-]{1,249}");
    private static final Pattern SERVERS = Pattern.compile("[A-Za-z0-9._:,-]+");

    /** The program that makes every table of {@code subscriptions}, in their order. */
    public static String render(List<Subscription> subscriptions) {
        StringBuilder b = new StringBuilder();
        b.append("// THE STARTUP PROGRAM, generated by legend-lite from the model: each landing table a Kafka subscription\n");
        b.append("// (docs/DESK_DATA_ROADMAP_2026_10_29.md B2). Written by the planner, never by hand.\n");
        b.append("import io.deephaven.kafka.KafkaTools\n");
        b.append("import io.deephaven.engine.table.ColumnDefinition\n");
        b.append("def legendKafka = { String servers ->\n");
        b.append("    def p = new Properties()\n");
        b.append("    p.put('bootstrap.servers', servers)\n");
        b.append("    p\n");
        b.append("}\n");
        for (Subscription s : subscriptions) {
            subscription(b, s);
        }
        return b.toString();
    }

    private static void subscription(StringBuilder b, Subscription s) {
        String where = "the table " + s.table() + " (topic " + s.topic() + ")";
        name(s.table(), where);
        if (!TOPIC.matcher(s.topic()).matches()) {
            throw new DialectCapability(where + ": '" + s.topic() + "' is no Kafka topic's name");
        }
        if (!SERVERS.matcher(s.bootstrapServers()).matches()) {
            throw new DialectCapability(where + ": '" + s.bootstrapServers() + "' is no list of brokers (host:port, ...)");
        }
        if (!"Json".equals(s.format())) {
            throw new DialectCapability(where + " is read from the " + s.format() + " topic: only a Json topic's"
                    + " subscription is generated yet");
        }
        if (s.keepFor() != null) {
            throw new DialectCapability(where + " keeps Last('" + s.keepFor() + "'): a retention over a time is not"
                    + " generated yet on Deephaven (keep its latest rows, LastRows(n))");
        }
        boolean keyed = !s.key().isEmpty();
        if (keyed && s.keepRows() != null) {
            throw new DialectCapability(where + " keeps each key's latest row, so it has no retention");
        }
        b.append(s.table()).append(" = KafkaTools.consumeToTable(legendKafka('").append(s.bootstrapServers())
                .append("'), '").append(s.topic()).append("', KafkaTools.ALL_PARTITIONS,")
                .append(" KafkaTools.ALL_PARTITIONS_SEEK_TO_BEGINNING, KafkaTools.Consume.IGNORE,")
                .append(" KafkaTools.Consume.jsonSpec([");
        for (int i = 0; i < s.columns().size(); i++) {
            Column c = s.columns().get(i);
            name(c.name(), where + "'s column");
            b.append(i > 0 ? ", " : "").append(definition(c, where));
        }
        b.append("] as ColumnDefinition[]), ");
        b.append(keyed ? "KafkaTools.TableType.blink()" : s.keepRows() != null
                ? "KafkaTools.TableType.ring(" + s.keepRows() + ")" : "KafkaTools.TableType.append()");
        b.append(")");
        // a day travels as its text: made a LocalDate on the server, a null kept a null
        List<Column> days = s.columns().stream().filter(c -> "java.time.LocalDate".equals(c.type())).toList();
        if (!days.isEmpty()) {
            b.append(".update(");
            for (int i = 0; i < days.size(); i++) {
                String n = days.get(i).name();
                b.append(i > 0 ? ", " : "").append("'").append(n).append(" = isNull(").append(n)
                        .append(") ? (java.time.LocalDate) null : java.time.LocalDate.parse(").append(n).append(")'");
            }
            b.append(")");
        }
        if (keyed) {
            b.append(".lastBy(");
            for (int i = 0; i < s.key().size(); i++) {
                name(s.key().get(i), where + "'s key");
                b.append(i > 0 ? ", " : "").append("'").append(s.key().get(i)).append("'");
            }
            b.append(")");
        }
        // the declared columns alone, in their order: Kafka's own columns left out
        b.append(".view(");
        for (int i = 0; i < s.columns().size(); i++) {
            b.append(i > 0 ? ", " : "").append("'").append(s.columns().get(i).name()).append("'");
        }
        b.append(")\n");
    }

    /** The column definition a topic's JSON is read by, by the Java type its column holds (a day read as text). */
    private static final java.util.Map<String, String> READ_AS = java.util.Map.of(
            "java.lang.String", "ofString", "java.time.LocalDate", "ofString", "double", "ofDouble", "float", "ofFloat",
            "int", "ofInt", "long", "ofLong", "short", "ofShort", "byte", "ofByte", "java.lang.Boolean", "ofBoolean",
            "java.time.Instant", "ofTime");

    private static String definition(Column c, String where) {
        String of = READ_AS.get(c.type());
        if (of == null) {
            throw new DialectCapability(where + ": its column " + c.name() + " is held as " + c.type()
                    + ", which no topic's subscription reads yet");
        }
        return "ColumnDefinition." + of + "('" + c.name() + "')";
    }

    private static void name(String name, String where) {
        if (!IDENTIFIER.matcher(name).matches()) {
            throw new DialectCapability(where + ": '" + name + "' is no name a Deephaven table or column takes here");
        }
    }
}
